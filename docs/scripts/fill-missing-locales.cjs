function i18nDeepMerge(base, over) {
  if (!over || typeof over !== 'object' || over === null) {
    return base && typeof base === 'object' ? JSON.parse(JSON.stringify(base)) : base;
  }
  if (!base || typeof base !== 'object' || base === null) {
    return JSON.parse(JSON.stringify(over));
  }
  const out = JSON.parse(JSON.stringify(base));
  for (const k in over) {
    if (!Object.prototype.hasOwnProperty.call(over, k)) continue;
    const bv = out[k];
    const ov = over[k];
    if (ov !== null && typeof ov === 'object' && !Array.isArray(ov) && (bv == null || (typeof bv === 'object' && !Array.isArray(bv)))) {
      out[k] = i18nDeepMerge(bv && typeof bv === 'object' ? bv : {}, ov);
    } else {
      out[k] = ov;
    }
  }
  return out;
}

